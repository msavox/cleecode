//! The built-in manual: the text shown by Help ▸ Manual (`Ctrl+Shift+M`), as a list of sections a
//! reader moves between rather than one long scroll. Plain text with ASCII diagrams, so it
//! renders identically wherever CleeCode does — no font, no colour, no markdown.
//!
//! Body lines are kept under ~76 columns: the reading pane is the modal width minus the
//! section list, and wrapping mid-diagram would ruin the pictures.

use crate::i18n::Lang;
use crate::keymap::Keymap;
use std::borrow::Cow;

pub struct Section {
    pub title: &'static str,
    /// The section's lines, with every chord the reader has moved written the way they moved it.
    ///
    /// `Cow`, because that rewriting is the exception: with nothing remapped — which is nearly
    /// every reader — these are the same static strings the source holds and not one byte is
    /// copied. See [`Keymap::relabel`].
    pub body: Vec<Cow<'static, str>>,
}

/// Where the reader is: which section, and how far down it. Held by `App` while the manual
/// is open.
pub struct ManualState {
    pub section: usize,
    pub scroll: usize,
}

impl ManualState {
    pub fn new() -> Self {
        ManualState { section: 0, scroll: 0 }
    }

    /// Moves to another section, always landing at its top — a scroll offset carried over
    /// from a longer section would open the next one part-way down.
    pub fn select(&mut self, index: usize, count: usize) {
        if count == 0 {
            return;
        }
        self.section = index.min(count - 1);
        self.scroll = 0;
    }

    pub fn cycle(&mut self, delta: isize, count: usize) {
        if count == 0 {
            return;
        }
        let len = count as isize;
        self.section = (((self.section as isize + delta) % len + len) % len) as usize;
        self.scroll = 0;
    }

    /// Scrolls within `len` lines shown `height` at a time, stopping at the last screenful
    /// rather than scrolling the text off the top.
    pub fn scroll_by(&mut self, delta: isize, len: usize, height: usize) {
        let max = len.saturating_sub(height.max(1));
        self.scroll = (self.scroll as isize + delta).clamp(0, max as isize) as usize;
    }
}

/// The manual as this reader's keyboard actually works.
///
/// The prose is written by hand and stays that way — it says *why* a key is the key it is, and a
/// generated table cannot say that — but the chords inside it are passed through the keymap on
/// the way out. A manual that advertised `Ctrl+Shift+H` to somebody who had moved project search
/// onto `Ctrl+Alt+F` would be worse than no manual: it would be a confident wrong answer, in the
/// one place a reader goes precisely because they do not know.
pub fn sections(lang: Lang, keymap: &Keymap) -> Vec<Section> {
    let pages = match lang {
        Lang::En => EN,
        Lang::It => IT,
    };
    pages
        .iter()
        .map(|(title, body)| Section {
            title,
            body: body.iter().map(|line| keymap.relabel(line)).collect(),
        })
        .collect()
}

